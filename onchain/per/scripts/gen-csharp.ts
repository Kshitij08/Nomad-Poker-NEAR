// Generates the C# bindings for the poker-per program from its IDL:
//   Assets/Scripts/Per/Core/Generated/PokerPerIdl.cs
// Plain C# (no Unity, no Solana SDK), so the same file compiles in Unity and in per/client-harness.
// Covers what the client needs: account decoders (with discriminator checks), instruction data
// encoders with their account lists, and the error table (the rollup returns only numeric codes).
//   npx tsx scripts/gen-csharp.ts            (writes the file)
//   npx tsx scripts/gen-csharp.ts --check    (fails if the file is stale)
import fs from "fs";
import path from "path";

const idl = JSON.parse(fs.readFileSync(path.join(__dirname, "../idl/poker_per.json"), "utf8"));
const OUT = path.join(__dirname, "../../Assets/Scripts/Per/Core/Generated/PokerPerIdl.cs");

const pascal = (s: string) => s.split("_").map((w) => w[0].toUpperCase() + w.slice(1)).join("");
const CS_KEYWORDS = new Set(["params", "object", "string", "event", "base", "class", "fixed", "checked", "default", "lock", "operator", "ref", "out"]);
/** A camelCase C# identifier, escaped with @ when it's a keyword. */
const camel = (s: string) => { const c = s.replace(/_(\w)/g, (_: string, x: string) => x.toUpperCase()); return CS_KEYWORDS.has(c) ? "@" + c : c; };
const types = new Map<string, any>(idl.types.map((t: any) => [t.name, t]));

/** C# type and reader/writer expressions for an IDL type. */
function csType(t: any): string {
  if (typeof t === "string") return ({ u8: "byte", i8: "sbyte", u16: "ushort", u32: "uint", u64: "ulong", i64: "long", bool: "bool", pubkey: "byte[]", string: "string", bytes: "byte[]" } as any)[t] ?? (() => { throw new Error(`type ${t}`); })();
  if (t.array) { const [inner] = t.array; return inner === "u8" ? "byte[]" : `${csType(inner)}[]`; }
  if (t.option) return csType(t.option);
  if (t.vec) return t.vec === "u8" ? "byte[]" : `${csType(t.vec)}[]`;
  if (t.defined) return t.defined.name;
  throw new Error(JSON.stringify(t));
}
function reader(t: any): string {
  if (typeof t === "string") return ({ u8: "r.U8()", i8: "(sbyte)r.U8()", u16: "r.U16()", u32: "r.U32()", u64: "r.U64()", i64: "r.I64()", bool: "r.Bool()", pubkey: "r.Bytes(32)", string: "r.Str()", bytes: "r.Bytes((int)r.U32())" } as any)[t];
  if (t.array) {
    const [inner, n] = t.array;
    return inner === "u8" ? `r.Bytes(${n})` : `r.Array(${n}, () => ${reader(inner)})`;
  }
  if (t.option) return `(r.Bool() ? ${reader(t.option)} : default)`;
  if (t.vec) return t.vec === "u8" ? "r.Bytes((int)r.U32())" : `r.Array((int)r.U32(), () => ${reader(t.vec)})`;
  if (t.defined) return `${t.defined.name}.Read(r)`;
  throw new Error(JSON.stringify(t));
}
function writer(t: any, v: string): string {
  if (typeof t === "string") return ({ u8: `w.U8(${v})`, u16: `w.U16(${v})`, u32: `w.U32(${v})`, u64: `w.U64(${v})`, i64: `w.I64(${v})`, bool: `w.Bool(${v})`, pubkey: `w.Fixed(${v}, 32)`, bytes: `w.Bytes(${v})` } as any)[t] ?? (() => { throw new Error(`write ${t}`); })();
  if (t.array && t.array[0] === "u8") return `w.Fixed(${v}, ${t.array[1]})`;
  if (t.option) return `w.Option(${v} != null, () => ${writer(t.option, `${v}`)})`;
  if (t.vec && typeof t.vec === "object" && t.vec.array?.[0] === "u8") return `w.VecOfFixed(${v}, ${t.vec.array[1]})`;
  if (t.vec) return `w.Vec(${v}, x => ${writer(t.vec, "x")})`;
  if (t.defined) return `${v}.Write(w)`;
  throw new Error(`write ${JSON.stringify(t)}`);
}

const lines: string[] = [];
const out = (s = "") => lines.push(s);
out("// <auto-generated> by per/scripts/gen-csharp.ts from per/idl/poker_per.json. Do not edit. </auto-generated>");
out(`// Program ${idl.address}`);
out("using System;");
out("using System.Collections.Generic;");
out("");
out("namespace Poker.Per.Generated");
out("{");
out("    public static class PokerPerProgram");
out("    {");
out(`        public const string ProgramId = "${idl.address}";`);
out("    }");
out("");

// Structs: every IDL type used by accounts or instruction args (events are skipped).
const accountNames = new Set(idl.accounts.map((a: any) => a.name));
const needed = new Set<string>();
const visit = (t: any) => {
  if (!t || typeof t === "string") return;
  if (t.array) return visit(t.array[0]);
  if (t.option) return visit(t.option);
  if (t.vec) return visit(t.vec);
  if (t.defined && !needed.has(t.defined.name)) { needed.add(t.defined.name); types.get(t.defined.name)?.type.fields?.forEach((f: any) => visit(f.type)); }
};
for (const ix of idl.instructions) for (const a of ix.args) visit(a.type);
const written = new Set(needed); // only instruction arguments are ever encoded
for (const a of idl.accounts) visit({ defined: { name: a.name } });

for (const name of [...needed].sort()) {
  const t = types.get(name);
  out(`    public sealed class ${name}`);
  out("    {");
  for (const f of t.type.fields) out(`        public ${csType(f.type)} ${pascal(f.name)};`);
  const acct = idl.accounts.find((a: any) => a.name === name);
  if (acct) {
    out(`        public static readonly byte[] Discriminator = { ${acct.discriminator.join(", ")} };`);
    out(`        /// <summary>Decodes the account's data (discriminator included); null if it isn't a ${name}.</summary>`);
    out(`        public static ${name} Decode(byte[] data)`);
    out("        {");
    out("            if (data == null || data.Length < 8) return null;");
    out("            for (int i = 0; i < 8; i++) if (data[i] != Discriminator[i]) return null;");
    out("            var r = new BorshReader(data, 8);");
    out("            try { return Read(r); } catch (IndexOutOfRangeException) { return null; } // an older, shorter layout");
    out("        }");
  }
  out(`        public static ${name} Read(BorshReader r)`);
  out("        {");
  out(`            var v = new ${name}();`);
  for (const f of t.type.fields) out(`            v.${pascal(f.name)} = ${reader(f.type)};`);
  out("            return v;");
  out("        }");
  if (written.has(name)) {
    out("        public void Write(BorshWriter w)");
    out("        {");
    for (const f of t.type.fields) out(`            ${writer(f.type, pascal(f.name))};`);
    out("        }");
  }
  out("    }");
  out("");
}

// Instructions: data encoders plus the flattened account list (name, writable, signer, fixed address).
out("    public sealed class IxAccount");
out("    {");
out("        public string Name; public bool Writable; public bool Signer; public string Address;");
out("        public IxAccount(string name, bool writable, bool signer, string address) { Name = name; Writable = writable; Signer = signer; Address = address; }");
out("    }");
out("");
out("    public static class Ix");
out("    {");
const flatten = (accts: any[], prefix = ""): any[] => accts.flatMap((a) => (a.accounts ? flatten(a.accounts, `${prefix}${a.name}.`) : [{ ...a, name: `${prefix}${a.name}` }]));
for (const ix of idl.instructions) {
  const fn = pascal(ix.name);
  const params = ix.args.map((a: any) => `${csType(a.type)} ${camel(a.name)}`).join(", ");
  out(`        public static readonly byte[] ${fn}Discriminator = { ${ix.discriminator.join(", ")} };`);
  out(`        public static byte[] ${fn}(${params})`);
  out("        {");
  out("            var w = new BorshWriter();");
  out(`            w.Raw(${fn}Discriminator);`);
  for (const a of ix.args) out(`            ${writer(a.type, camel(a.name))};`);
  out("            return w.ToArray();");
  out("        }");
  out(`        public static readonly IxAccount[] ${fn}Accounts =`);
  out("        {");
  for (const a of flatten(ix.accounts)) out(`            new IxAccount("${a.name}", ${!!a.writable}, ${!!a.signer}, ${a.address ? `"${a.address}"` : "null"}),`);
  out("        };");
}
out("    }");
out("");

// Errors.
out("    public static class PokerPerErrors");
out("    {");
out("        public static readonly Dictionary<uint, (string Name, string Message)> ByCode = new Dictionary<uint, (string, string)>");
out("        {");
for (const e of idl.errors) out(`            { ${e.code}, ("${e.name}", ${JSON.stringify(e.msg ?? e.name)}) },`);
out("        };");
out("    }");
out("}");

const text = lines.join("\n") + "\n";
if (process.argv.includes("--check")) {
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
  if (cur !== text) { console.error("stale: run npx tsx scripts/gen-csharp.ts"); process.exit(1); }
  console.log("up to date");
} else {
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, text);
  console.log(`wrote ${OUT} (${lines.length} lines)`);
}
