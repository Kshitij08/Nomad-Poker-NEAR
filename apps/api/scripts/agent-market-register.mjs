#!/usr/bin/env node
// Lists the Nomad Poker scout on the NEAR AI Agent Market (https://market.near.ai), one explicit step at a time.
// Nothing runs without a command; each command makes only the calls it names. API: https://market.near.ai/openapi.json
//
//   node scripts/agent-market-register.mjs register      POST /v1/agents/register: creates the agent (a draft) and
//                                                         saves its aat_ token, its id and a new webhook secret to
//                                                         .secrets.agent-market.json (git-ignored). The token is shown once.
//   node scripts/agent-market-register.mjs configure     PATCH /v1/agents/{id}: listing text, tags, SLA, webhook_url + webhook_secret
//   node scripts/agent-market-register.mjs price         POST /v1/agents/{id}/pricing-plans: one per_call plan (AGENT_MARKET_PRICE, default 0.00)
//   node scripts/agent-market-register.mjs test          POST /v1/agents/{id}/webhook/test: a signed webhook.ping to the deployed API
//   node scripts/agent-market-register.mjs publish       PATCH /v1/agents/{id} {listing_status: "live"} (needs a live default plan;
//                                                         the market may also want a confirmed email first)
//   node scripts/agent-market-register.mjs unpublish     PATCH /v1/agents/{id} {listing_status: "paused"}
//   node scripts/agent-market-register.mjs status        GET /v1/agents/{id} and its pricing plans
//   node scripts/agent-market-register.mjs adopt-code    POST /v1/agents/me/adoption-code: a link that moves the agent into your
//                                                         market.near.ai account (needed for Discover and for payouts)
//
// Env (all optional; values saved by `register` are used when unset):
//   AGENT_MARKET_API             default https://market.near.ai
//   AGENT_MARKET_TOKEN           the agent's aat_ token
//   AGENT_MARKET_AGENT_ID        the agent's id (uuid)
//   AGENT_MARKET_WEBHOOK_SECRET  32+ characters; generated by `register` when unset
//   AGENT_MARKET_WEBHOOK_URL     default https://nomad-poker-near-api-staging.kshitijiitgn.workers.dev/v1/agent-market/webhook
//   AGENT_MARKET_HANDLE          default nomad-poker-scout (3-30 chars, [a-z][a-z0-9-]*, permanent: it becomes <handle>.market.near.ai)
//   AGENT_MARKET_CATEGORY        default data
//   AGENT_MARKET_EMAIL           optional contact address for the agent
//   AGENT_MARKET_PRICE           default 0.00 (USDC per call); if the market refuses it, the error says so: retry with e.g. 0.01

import { randomBytes } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const SAVED = join(dirname(fileURLToPath(import.meta.url)), '..', '.secrets.agent-market.json');
const saved = existsSync(SAVED) ? JSON.parse(readFileSync(SAVED, 'utf8')) : {};
const env = (k, d) => process.env[k] || saved[k] || d;

const API = env('AGENT_MARKET_API', 'https://market.near.ai').replace(/\/+$/, '');
const HANDLE = env('AGENT_MARKET_HANDLE', 'nomad-poker-scout');
const WEBHOOK_URL = env('AGENT_MARKET_WEBHOOK_URL', 'https://nomad-poker-near-api-staging.kshitijiitgn.workers.dev/v1/agent-market/webhook');
const SLA_SECONDS = 600;

const LISTING = {
  name: 'Nomad Poker Scout',
  description: "Verified track record of any Nomad Poker AI pro on NEAR: sessions, hands, results, backers' pool value and change.",
  tags: ['poker', 'near', 'on-chain', 'copy-trading', 'ai-agents', 'testnet'],
  bio_markdown: `**Nomad Poker Scout** reads the Nomad Poker table contract (\`table.nomad-poker.testnet\`) on NEAR testnet and reports on the AI poker pros listed there, so you can decide whom to back.

**Ask for** an agent by id (\`nomad-a\`), a style ("a tight aggressive pro") or nothing at all (the whole field, ranked).

**You get** a Markdown report:
- the agent's verified record: backed sessions, hands played, chips won or lost;
- its backers' pool: value, change since it opened, high-water mark, how much one session may risk;
- its recent settled sessions with buy-in, cash-out and result, and how to watch each one re-dealt from the dealer's randomness proof in the Nomad Poker app;
- how to back it, and the contract views to check every number yourself.

Sessions are dealt by a sealed OutLayer dealer and verified on chain before they settle. This is a hackathon build on **NEAR testnet**: testnet NEAR has no cash value, and past results do not predict future ones. Reports usually arrive within seconds.`,
};

function save(patch) {
  Object.assign(saved, patch);
  writeFileSync(SAVED, JSON.stringify(saved, null, 2) + '\n', { mode: 0o600 });
}

async function call(method, path, body, { auth = true } = {}) {
  const headers = { accept: 'application/json' };
  if (body !== undefined) headers['content-type'] = 'application/json';
  if (auth) {
    const token = env('AGENT_MARKET_TOKEN');
    if (!token) throw new Error('No agent token: run `register` first or set AGENT_MARKET_TOKEN.');
    headers.authorization = `Bearer ${token}`;
  }
  const res = await fetch(API + path, { method, headers, body: body === undefined ? undefined : JSON.stringify(body) });
  const text = await res.text();
  let json = null;
  try {
    json = text ? JSON.parse(text) : null;
  } catch {
    json = text;
  }
  if (!res.ok) throw new Error(`${method} ${path} answered ${res.status}: ${typeof json === 'string' ? json : JSON.stringify(json)}`);
  return json;
}

const agentId = () => {
  const id = env('AGENT_MARKET_AGENT_ID');
  if (!id) throw new Error('No agent id: run `register` first or set AGENT_MARKET_AGENT_ID.');
  return id;
};

const commands = {
  async register() {
    if (saved.AGENT_MARKET_TOKEN) throw new Error(`Already registered (${saved.AGENT_MARKET_HANDLE} ${saved.AGENT_MARKET_AGENT_ID}); see ${SAVED}.`);
    const body = { handle: HANDLE, name: LISTING.name, category: env('AGENT_MARKET_CATEGORY', 'data'), sla_seconds: SLA_SECONDS };
    const email = env('AGENT_MARKET_EMAIL');
    if (email) body.email = email;
    const r = await call('POST', '/v1/agents/register', body, { auth: false });
    const secret = env('AGENT_MARKET_WEBHOOK_SECRET') || randomBytes(32).toString('hex');
    save({ AGENT_MARKET_AGENT_ID: r.agentId, AGENT_MARKET_ACCOUNT_ID: r.accountId, AGENT_MARKET_HANDLE: r.handle, AGENT_MARKET_TOKEN: r.apiToken, AGENT_MARKET_WEBHOOK_SECRET: secret });
    console.log(`Registered ${r.handle} (agent ${r.agentId}, account ${r.accountId}) as a draft.`);
    console.log(`Token (${r.tokenPrefix}…) and webhook secret saved to ${SAVED}; the market never shows the token again.`);
    console.log('Next: add AGENT_MARKET_TOKEN and AGENT_MARKET_WEBHOOK_SECRET from that file to apps/api/.secrets.staging.json, deploy the API, then run `configure`.');
  },

  async configure() {
    const secret = env('AGENT_MARKET_WEBHOOK_SECRET');
    if (!secret || secret.length < 32) throw new Error('AGENT_MARKET_WEBHOOK_SECRET must be 32+ characters (run `register`, or set it).');
    const r = await call('PATCH', `/v1/agents/${agentId()}`, { ...LISTING, runtime: 'http', sla_seconds: SLA_SECONDS, webhook_url: WEBHOOK_URL, webhook_secret: secret, webhook_enabled: true });
    console.log(`Configured ${r.handle ?? HANDLE}: webhook ${WEBHOOK_URL}, listing ${r.listing_status ?? '?'}.`);
  },

  async price() {
    const amount = env('AGENT_MARKET_PRICE', '0.00');
    const plans = await call('GET', `/v1/agents/${agentId()}/pricing-plans`);
    if (plans.length) {
      console.log(`The agent already has ${plans.length} plan(s); not adding another:`);
      for (const p of plans) console.log(`  ${p.pricing_plan_id} ${p.model} ${p.price_amount} ${p.listing_status}${p.is_default ? ' (default)' : ''}`);
      return;
    }
    const p = await call('POST', `/v1/agents/${agentId()}/pricing-plans`, {
      model: 'per_call',
      price_amount: amount,
      display_name: 'Scout report',
      description: 'One scout report on a Nomad Poker agent, a style, or the whole field.',
      sla_seconds: SLA_SECONDS,
    });
    console.log(`Plan ${p.pricing_plan_id}: ${p.model} ${p.price_amount}, ${p.listing_status}${p.is_default ? ', default' : ''}.`);
    if (p.listing_status !== 'live') {
      await call('PATCH', `/v1/pricing-plans/${p.pricing_plan_id}`, { listing_status: 'live' });
      console.log('Plan set live.');
    }
    if (!p.is_default) {
      await call('POST', `/v1/pricing-plans/${p.pricing_plan_id}/make-default`);
      console.log('Plan made the default.');
    }
  },

  async test() {
    const r = await call('POST', `/v1/agents/${agentId()}/webhook/test`);
    console.log(r.ok ? `Webhook OK (HTTP ${r.http_status}, ${r.duration_ms} ms).` : `Webhook FAILED: ${r.error ?? `HTTP ${r.http_status}`} ${r.response_body_preview ?? ''}`);
    if (!r.ok) process.exitCode = 1;
  },

  async publish() {
    const r = await call('PATCH', `/v1/agents/${agentId()}`, { listing_status: 'live' });
    console.log(`${r.handle ?? HANDLE} is ${r.listing_status}: https://market.near.ai/agents/${r.handle ?? HANDLE}`);
  },

  async unpublish() {
    const r = await call('PATCH', `/v1/agents/${agentId()}`, { listing_status: 'paused' });
    console.log(`${r.handle ?? HANDLE} is ${r.listing_status}.`);
  },

  async status() {
    const a = await call('GET', `/v1/agents/${agentId()}`);
    const plans = await call('GET', `/v1/agents/${agentId()}/pricing-plans`);
    console.log(JSON.stringify({ handle: a.handle, name: a.name, listing_status: a.listing_status, runtime: a.runtime, webhook_url: a.webhook_url, webhook_enabled: a.webhook_enabled, plans: plans.map((p) => ({ id: p.pricing_plan_id, model: p.model, price: p.price_amount, status: p.listing_status, default: p.is_default })) }, null, 2));
  },

  async 'adopt-code'() {
    const r = await call('POST', '/v1/agents/me/adoption-code');
    console.log(`Open this while signed in to market.near.ai to adopt the agent (single use, until ${r.expiresAt}):\n${r.adoptionUrl}`);
  },
};

const cmd = process.argv[2];
if (!cmd || !commands[cmd]) {
  console.log(readFileSync(fileURLToPath(import.meta.url), 'utf8').split('\n').slice(1, 30).filter((l) => l.startsWith('//')).map((l) => l.slice(3)).join('\n'));
  process.exit(cmd ? 1 : 0);
}
try {
  await commands[cmd]();
} catch (e) {
  console.error(e instanceof Error ? e.message : e);
  process.exit(1);
}
