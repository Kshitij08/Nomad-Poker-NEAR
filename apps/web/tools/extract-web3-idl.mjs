// Slims the Anchor IDLs of the two Solana programs the client talks to into what src/web3 needs:
//   per/idl/poker_per.json       → src/data/web3-per-idl.json     (private tables, MagicBlock TEE rollup)
//   shared/idl/poker_escrow.json → src/data/web3-escrow-idl.json  (escrow money tables)
// Same selection as per/scripts/gen-csharp.ts (which generates Assets/Scripts/Per/Core/Generated/PokerPerIdl.cs):
// every type an account or an instruction argument uses, each instruction's discriminator, args and FLATTENED
// account list (nested groups become "group.name", exactly like the C# IxAccount names), account
// discriminators, and the error table. Docs and events are dropped (the full IDL is ~366 KB).
//   node web/tools/extract-web3-idl.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, '../..');

function slim(idl) {
  const types = new Map(idl.types.map((t) => [t.name, t]));
  const needed = new Set();
  const visit = (t) => {
    if (!t || typeof t === 'string') return;
    if (t.array) return visit(t.array[0]);
    if (t.option) return visit(t.option);
    if (t.vec) return visit(t.vec);
    if (t.defined && !needed.has(t.defined.name)) {
      needed.add(t.defined.name);
      const def = types.get(t.defined.name);
      def?.type.fields?.forEach((f) => visit(f.type));
      def?.type.variants?.forEach((v) => v.fields?.forEach((f) => visit(f.type ?? f)));
    }
  };
  for (const ix of idl.instructions) for (const a of ix.args) visit(a.type);
  for (const a of idl.accounts ?? []) visit({ defined: { name: a.name } });
  const flatten = (accts, prefix = '') =>
    accts.flatMap((a) =>
      a.accounts
        ? flatten(a.accounts, `${prefix}${a.name}.`)
        : [{ name: `${prefix}${a.name}`, w: a.writable ? 1 : 0, s: a.signer ? 1 : 0, ...(a.address ? { addr: a.address } : {}), ...(a.optional ? { opt: 1 } : {}) }],
    );
  const typeOut = {};
  for (const name of [...needed].sort()) {
    const t = types.get(name);
    if (!t) throw new Error(`type ${name} missing`);
    if (t.type.kind === 'struct') typeOut[name] = { kind: 'struct', fields: t.type.fields.map((f) => [f.name, f.type]) };
    else if (t.type.kind === 'enum') typeOut[name] = { kind: 'enum', variants: t.type.variants.map((v) => v.name) };
    else throw new Error(`type kind ${t.type.kind}`);
  }
  return {
    address: idl.address,
    source: 'generated by web/tools/extract-web3-idl.mjs; do not edit',
    instructions: Object.fromEntries(
      idl.instructions.map((ix) => [ix.name, { d: ix.discriminator, args: ix.args.map((a) => [a.name, a.type]), accounts: flatten(ix.accounts) }]),
    ),
    accounts: Object.fromEntries((idl.accounts ?? []).map((a) => [a.name, a.discriminator])),
    types: typeOut,
    errors: Object.fromEntries((idl.errors ?? []).map((e) => [e.code, [e.name, e.msg ?? e.name]])),
  };
}

for (const [src, out] of [
  ['per/idl/poker_per.json', 'web/src/data/web3-per-idl.json'],
  ['shared/idl/poker_escrow.json', 'web/src/data/web3-escrow-idl.json'],
]) {
  const idl = JSON.parse(fs.readFileSync(path.join(repo, src), 'utf8'));
  const json = JSON.stringify(slim(idl));
  fs.writeFileSync(path.join(repo, out), json + '\n');
  console.log(`${src} → ${out} (${(json.length / 1024).toFixed(1)} KB)`);
}
